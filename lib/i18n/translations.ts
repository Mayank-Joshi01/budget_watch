const translations: Record<Language, Readonly<Record<string, string>>> = {
  en: {},
  hi: hindiTranslations,
};

function normalizeTranslationKey(value: string) {
  return value.replace(/\s+/g, " ").trim();
}

const englishByHindi = new Map(
  Object.entries(hindiTranslations).map(([english, hindi]) => [hindi, english]),
);

export function translate(language: Language, key: string): string {
  if (language === "en") return key;
  const normalized = normalizeTranslationKey(key);
  return translations[language][normalized] ?? key;
}

export function translateText(language: Language, value: string): string {
  if (language === "en") return value;
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return value;
  const [, leading, content, trailing] = match;
  let translated = translate(language, content);

  if (translated === content) {
    let dynamicMatch = content.match(/^Rank movement from (.+) to (.+)$/);
    if (dynamicMatch) {
      translated = `${translate(language, "Rank movement from")} ${dynamicMatch[1]} ${translate(language, "to")} ${dynamicMatch[2]}`;
    } else {
      dynamicMatch = content.match(/^(.+) vs (.+)$/);
      if (dynamicMatch) {
        translated = `${dynamicMatch[1]} ${translate(language, "vs")} ${dynamicMatch[2]}`;
      } else {
        dynamicMatch = content.match(/^No allocation in (.+)$/);
        if (dynamicMatch) {
          translated = `${translate(language, "No allocation in")} ${dynamicMatch[1]}`;
        } else {
          dynamicMatch = content.match(/^No allocation data for (.+)$/);
          if (dynamicMatch) {
            translated = `${translate(language, "No allocation data for")} ${dynamicMatch[1]}`;
          } else {
            dynamicMatch = content.match(/^(\d+)–(\d+) of (\d+) departments$/);
            if (dynamicMatch) {
              translated = `${dynamicMatch[1]}–${dynamicMatch[2]} ${translate(language, "of")} ${dynamicMatch[3]} ${translate(language, "departments")}`;
            } else {
              dynamicMatch = content.match(/^(.+) · ₹ crore$/);
              if (dynamicMatch) {
                translated = `${dynamicMatch[1]} · ${translate(language, "₹ crore")}`;
              }
            }
          }
        }
      }
    }
  }

  return `${leading}${translated}${trailing}`;
}

export function getEnglishSource(value: string): string {
  const match = value.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return value;
  const [, leading, content, trailing] = match;
  const english = englishByHindi.get(content) ?? content;
  return `${leading}${english}${trailing}`;
}
